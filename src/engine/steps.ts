/**
 * 引擎内置的远端命令常量。
 *
 * 判据（ADR-0047）：引擎在实例里执行的命令只有一条，且由引擎自己写死。
 * 它不读任何配置，不拼使用者的文本，也不依赖实例内的目录。
 */

/**
 * 探测命令。
 *
 * 判据：`probe` 只回答「SSH 能不能连上并执行一条命令」。连不上在 SSH 层失败；
 * 命令层失败看退出码。所以命令必须恒真、无输出、不读任何目录或配置。
 * 业务服务是否起来不归它判断，因此不用 `ss -ltn` 这类验端口的命令。
 */
export const PROBE_COMMAND = 'true'

/**
 * 探测的超时，秒。
 *
 * 判据：`true` 在远端零耗时执行。30 秒还没返回，说明建连或会话链路坏了，
 * 再等也不会变好。它不是服务慢的等待窗口：服务慢由使用者自己判断。
 */
export const PROBE_TIMEOUT_SECONDS = 30
